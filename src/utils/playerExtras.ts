import { useEffect, useMemo, useRef, useState } from 'react';
import { dataJson } from '@/utils/dataStore';

// Optional per-player extras from public/data/player-extras.json (built by scripts/build_league_data.py).
// Everything here is secondary display info and must never be merged into league career totals.

/** Pre-league real NFL career line. Keys vary by position; `years` is e.g. "2018-2025". */
export type RealNflCareer = { years?: string } & Record<string, number | string | undefined>;

/** In-game player card extras; any subset of keys may be present. */
export type PlayerCardExtras = Record<string, number | string | boolean | undefined>;

/** One reconstructed career stop (data/y80/stints.json). Years are save seasons (Y1–Y80; Y81 = joined after Y80). */
export interface CareerStint {
  team: string;
  from: number;
  to: number;
  /** Super Bowl years won during this stint */
  rings: number[];
}

export type StintConfidence = 'confirmed' | 'strong' | 'likely' | 'ambiguous';

export interface PlayerStints {
  stints: CareerStint[];
  confidence: StintConfidence;
  evidence: string;
  /** Years are a placeholder; only the team is known */
  approx?: boolean;
  /** Real-NFL rings on his card, won before the save */
  preLeagueRings?: number;
  alternatives?: { team: string; from: number; to: number }[][];
}

export interface PlayerExtras {
  realNflCareer: Record<string, RealNflCareer>;
  cards: Record<string, PlayerCardExtras>;
  /** current name -> former name */
  formerNames: Record<string, string>;
  /** player name -> relation text, e.g. "son of Tyrion Kline" */
  family: Record<string, string>;
  /** player name -> every franchise he played for (full names), when more than his final team is known */
  franchises: Record<string, string[]>;
  /** player name -> reconstructed career stints, in order */
  stints: Record<string, PlayerStints>;
  /**
   * player name -> the franchise he is best known for (full name): his card / banner identity (jersey, helmet,
   * colours, logo). Generated by scripts/build_league_data.py (owner fact, else the stint with the most rings).
   */
  signatureTeams: Record<string, string>;
  /** NFL edition: "POS:Name" -> his real jersey number */
  realNumbers?: Record<string, number>;
  /** NFL edition: careers from Wikipedia, "POS:Name" -> {d debut, l last season, c no weekly lines, m stats the page lacks, e games estimated} */
  classics?: Record<string, ClassicNote>;
  /**
   * player name -> where he is best known when that differs from his banner (an active player traded away from his
   * best years): the club that retires a Hall of Famer's number. Absent = his banner club.
   */
  legacyTeams?: Record<string, string>;
  /** player name -> the clubs that retired his number (owner), the first numbering him; absent = his best-known club */
  retiredBy?: Record<string, string[]>;
}

/** A career taken from Wikipedia (scripts/nfl/fetch_classics.py): debut, last season, `c` = no weekly data at all, `m` = stats the page lacks, `e` = games estimated. */
export interface ClassicNote {
  d: number;
  l: number;
  c?: 1;
  m?: string[];
  e?: 1;
}

const EMPTY: PlayerExtras = { realNflCareer: {}, cards: {}, formerNames: {}, family: {}, franchises: {}, stints: {}, signatureTeams: {}, legacyTeams: {}, retiredBy: {} };

/** Name key that ignores case, extra spaces and curly vs straight apostrophes/quotes. */
export const normalizeName = (name: string) =>
  name
    .replace(/[‘’ʼ`´]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();

const reindex = <T,>(rec: unknown): Record<string, T> => {
  const out: Record<string, T> = {};
  if (rec && typeof rec === 'object') {
    Object.entries(rec as Record<string, T>).forEach(([k, v]) => {
      out[normalizeName(k)] = v;
    });
  }
  return out;
};

/** Original-cased map, keyed by normalized name (used where the display name matters). */
const reindexWithName = (rec: unknown): Record<string, { name: string; value: string }> => {
  const out: Record<string, { name: string; value: string }> = {};
  if (rec && typeof rec === 'object') {
    Object.entries(rec as Record<string, unknown>).forEach(([k, v]) => {
      if (typeof v === 'string') out[normalizeName(k)] = { name: k, value: v };
    });
  }
  return out;
};

export interface IndexedExtras {
  realNflCareer: Record<string, RealNflCareer>;
  cards: Record<string, PlayerCardExtras>;
  formerNames: Record<string, string>;
  family: Record<string, { name: string; value: string }>;
  franchises: Record<string, string[]>;
  stints: Record<string, PlayerStints>;
  signatureTeams: Record<string, string>;
  realNumbers?: Record<string, number>;
  classics?: Record<string, ClassicNote>;
  legacyTeams: Record<string, string>;
  retiredBy: Record<string, string[]>;
}

const CONFIDENCE = new Set<StintConfidence>(['confirmed', 'strong', 'likely', 'ambiguous']);

/** Keeps only well-formed stint records (a bad row is dropped, never thrown). */
const normalizeStints = (rec: unknown): Record<string, PlayerStints> => {
  const out: Record<string, PlayerStints> = {};
  Object.entries(reindex<Partial<PlayerStints>>(rec)).forEach(([k, v]) => {
    const stints = (Array.isArray(v?.stints) ? v.stints : [])
      .filter((s): s is CareerStint => !!s && typeof s.team === 'string' && Number.isFinite(s.from) && Number.isFinite(s.to))
      .map((s) => ({ team: s.team, from: s.from, to: s.to, rings: Array.isArray(s.rings) ? s.rings.filter(Number.isFinite) : [] }));
    if (!stints.length) return;
    out[k] = {
      stints,
      confidence: v.confidence && CONFIDENCE.has(v.confidence) ? v.confidence : 'likely',
      evidence: typeof v.evidence === 'string' ? v.evidence : '',
      approx: v.approx === true || undefined,
      preLeagueRings: typeof v.preLeagueRings === 'number' ? v.preLeagueRings : undefined,
      alternatives: Array.isArray(v.alternatives) ? v.alternatives : undefined,
    };
  });
  return out;
};

const toIndexed = (raw: Partial<PlayerExtras>): IndexedExtras => ({
  realNflCareer: reindex<RealNflCareer>(raw.realNflCareer),
  cards: reindex<PlayerCardExtras>(raw.cards),
  formerNames: reindex<string>(raw.formerNames),
  family: reindexWithName(raw.family),
  franchises: reindex<string[]>(raw.franchises),
  stints: normalizeStints(raw.stints),
  realNumbers: raw.realNumbers,
  classics: raw.classics,
  signatureTeams: Object.fromEntries(Object.entries(reindex<unknown>(raw.signatureTeams)).filter((e): e is [string, string] => typeof e[1] === 'string')),
  legacyTeams: Object.fromEntries(Object.entries(reindex<unknown>(raw.legacyTeams)).filter((e): e is [string, string] => typeof e[1] === 'string')),
  retiredBy: Object.fromEntries(
    Object.entries(reindex<unknown>(raw.retiredBy)).filter((e): e is [string, string[]] => Array.isArray(e[1]) && e[1].every((t) => typeof t === 'string') && e[1].length > 0),
  ),
});

const EMPTY_INDEXED = toIndexed(EMPTY);

/*
 * Loading. The CORE extras (data/core/extras.json: banner and legacy teams, real numbers, retired-by, former names,
 * cards, family, real NFL careers) is what every page needs to dress a player, and it is all the startup fetches. The
 * HISTORY (data/history/stints.json and franchises.json: the heavy part, about half the old file) loads the first time a
 * component READS `extras.stints` / `extras.franchises` (the object usePlayerExtras() returns has getters that start the
 * load and re-render the reader when it lands), so pages that never look at a career (search, the games, the binder) never
 * pay for it. Both fall back to the old single file data/player-extras.json when the split files aren't there.
 */
let cache: IndexedExtras | null = null;
let inflight: Promise<IndexedExtras> | null = null;
let history: { stints: Record<string, PlayerStints>; franchises: Record<string, string[]> } | null = null;
let historyJob: Promise<void> | null = null;
const historyListeners = new Set<() => void>();

const loadSplit = async (): Promise<Partial<PlayerExtras>> => {
  const core = await dataJson<Partial<PlayerExtras>>('data/core/extras.json');
  if (core) return core;
  // No split files (a checkout that hasn't run scripts/perf/build_core.py): the whole file, stints and all
  const whole = await dataJson<Partial<PlayerExtras>>('data/player-extras.json');
  if (whole) {
    history = { stints: normalizeStints(whole.stints), franchises: reindex<string[]>(whole.franchises) };
    return { ...whole, stints: {}, franchises: {} };
  }
  return EMPTY;
};

/** Fetches the core extras once per session. Missing file (404) or bad JSON resolves to empty extras. */
export const loadPlayerExtras = (): Promise<IndexedExtras> => {
  if (cache) return Promise.resolve(cache);
  inflight ??= loadSplit()
    .catch(() => EMPTY)
    .then((raw) => {
      cache = toIndexed(raw ?? EMPTY);
      return cache;
    });
  return inflight;
};

/** Starts loading the career history (idempotent); resolves when it is in. */
export const loadExtrasHistory = (): Promise<void> => {
  historyJob ??= (async () => {
    await loadPlayerExtras(); // the whole-file fallback fills `history` there
    if (!history) {
      const [stints, franchises] = await Promise.all([
        dataJson<Record<string, unknown>>('data/history/stints.json'),
        dataJson<Record<string, string[]>>('data/history/franchises.json'),
      ]);
      history = { stints: normalizeStints(stints ?? {}), franchises: reindex<string[]>(franchises ?? {}) };
    }
    historyListeners.forEach((l) => l());
  })();
  return historyJob;
};

const NO_STINTS: Record<string, PlayerStints> = {};
const NO_FRANCHISES: Record<string, string[]> = {};

/**
 * React hook: empty extras until loaded, then the indexed file contents. `.stints` and `.franchises` read through
 * getters (see above): reading one starts the history load and re-renders this component when it arrives.
 */
export const usePlayerExtras = (): IndexedExtras => {
  const [core, setCore] = useState<IndexedExtras>(cache ?? EMPTY_INDEXED);
  const [historyIn, setHistoryIn] = useState(!!history);
  const touched = useRef(false);
  useEffect(() => {
    if (cache) return;
    let alive = true;
    loadPlayerExtras().then((e) => alive && setCore(e));
    return () => {
      alive = false;
    };
  }, []);
  useEffect(() => {
    if (!touched.current || historyIn) return;
    const l = () => setHistoryIn(true);
    historyListeners.add(l);
    if (history) setHistoryIn(true);
    return () => {
      historyListeners.delete(l);
    };
  });
  return useMemo(() => {
    const view = { ...core } as IndexedExtras;
    Object.defineProperty(view, 'stints', {
      enumerable: true,
      get: () => {
        touched.current = true;
        if (!history) void loadExtrasHistory();
        return history?.stints ?? NO_STINTS;
      },
    });
    Object.defineProperty(view, 'franchises', {
      enumerable: true,
      get: () => {
        touched.current = true;
        if (!history) void loadExtrasHistory();
        return history?.franchises ?? NO_FRANCHISES;
      },
    });
    return view;
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [core, historyIn]);
};

/** A player's reconstructed stints, or undefined when none are on file. */
export const getStints = (extras: IndexedExtras, playerName: string): PlayerStints | undefined => extras.stints[normalizeName(playerName)];

/**
 * The team a player's card and banners wear (signatureTeams): his current team while he plays, where he was best
 * known once he retires (scripts/build_league_data.py signature_teams); else his current team.
 * Only for identity (jersey, helmet, colours, logo); stats, rosters and team filters keep `player.team`.
 */
export const signatureTeamOf = (extras: IndexedExtras, player: { name: string; team?: string; isRealLegend?: boolean }): string =>
  (!player.isRealLegend && extras.signatureTeams[normalizeName(player.name)]) || player.team || '';

/** The club to show a player in (search, games, logos, colours): `bannerTeam` from the league load, else his team. */
export const bannerTeamOf = (p: { team?: string; bannerTeam?: string }): string => p.bannerTeam || p.team || '';

/** Where a player is best known even while he plays (the club that retires a Hall of Famer's number); else his banner. */
export const legacyTeamOf = (extras: IndexedExtras, player: { name: string; team?: string; isRealLegend?: boolean }): string =>
  (!player.isRealLegend && extras.legacyTeams[normalizeName(player.name)]) || signatureTeamOf(extras, player);

/** Every club that retires a Hall of Famer's number: the owner's list, else his best-known club alone. */
export const retiringClubsOf = (extras: IndexedExtras, player: { name: string; team?: string; isRealLegend?: boolean }): string[] =>
  (!player.isRealLegend && extras.retiredBy[normalizeName(player.name)]) || [legacyTeamOf(extras, player)].filter(Boolean);

/** The player dressed in his signature team (same object when it already matches), for card and banner art. */
export const withSignatureTeam = <P extends { name: string; team?: string; isRealLegend?: boolean }>(extras: IndexedExtras, player: P): P => {
  const team = signatureTeamOf(extras, player);
  return team === (player.team ?? '') ? player : { ...player, team };
};

export interface FamilyTie {
  /** Relation text as shown, e.g. "Son of" or "Family" */
  label: string;
  /** The other player's name */
  name: string;
}

/**
 * Family ties for a player: their own entry ("son of X" -> Son of X) plus reverse links from players
 * who list them ("Y: son of <player>" -> Y, son).
 */
export const getFamilyTies = (extras: IndexedExtras, playerName: string): FamilyTie[] => {
  const me = normalizeName(playerName);
  const ties: FamilyTie[] = [];
  const parse = (text: string) => {
    const m = text.match(/^\s*(.+?)\s+of\s+(.+?)\s*$/i);
    return m ? { relation: m[1], other: m[2] } : null;
  };
  const own = extras.family[me];
  if (own) {
    const p = parse(own.value);
    if (p) ties.push({ label: `${p.relation[0].toUpperCase()}${p.relation.slice(1)} of`, name: p.other });
  }
  Object.entries(extras.family).forEach(([key, { name, value }]) => {
    if (key === me) return;
    const p = parse(value);
    if (p && normalizeName(p.other) === me) ties.push({ label: `Family (${p.relation.toLowerCase()})`, name });
  });
  return ties;
};

/** The Wikipedia-career note of a player (pre-1999 careers), if he has one. */
export const classicNoteOf = (extras: IndexedExtras, player: { name: string; position: string }): ClassicNote | undefined =>
  extras.classics?.[`${player.position}:${player.name}`];
